from pathlib import Path
import json,re
import numpy as np
G=Path(__file__).resolve().parent/'output'

def rawfile(path):
    b=path.read_bytes();p=b.index(b'Binary:\n')+8;names=re.findall(r'^\s*\d+\s+(\S+)\s+\S+',b[:p].decode(),re.M)
    a=np.frombuffer(b[p:],dtype='<f8').reshape(-1,len(names));return {n:a[:,j] for j,n in enumerate(names)}

def analyze(tag):
    meta=json.loads((G/(tag+'.json')).read_text());raw=rawfile(G/(tag+'.raw'));t0=raw['time'];start=50e-6;end=.02005
    if t0[-1]<end-1e-12:return {'complete':False,'last_time_s':float(t0[-1])}
    t=np.unique(np.r_[start,t0[(t0>start)&(t0<end)],end]);d={n:np.interp(t,t0,x) for n,x in raw.items()};avg=lambda x:float(np.trapezoid(x,t)/.02)
    z=np.zeros_like(t);additional=z.copy();gate=z.copy();path=[];vg=[];vd=[];charge_energy=0
    rd=(1-.3229)*.001975*1.015;rs=.3229*.001975*1.015;si=1545*.00075;so=1545*.0039;sr=1545
    diode=lambda v:.125*1545/1077*(4.3e-7*np.expm1(np.minimum(v,10)/.8)+2.6e-13*np.expm1(np.minimum(v,10)/.23))
    soft=lambda x:np.logaddexp(0,x)
    for j in range(1,7):
        phase='abc'[(j-1)%3];vs=d[f'v({phase})'] if j<=3 else z;extd=d['v(bus)'] if j<=3 else d[f'v({phase})']
        vi=d[f'v(xq{j}.drain)'];ss=d[f'v(xq{j}.source)'];gi=d[f'v(xq{j}.gate)'];ge=d[f'v(g{j})'];vds=vi-ss;vgs=gi-ss;vgd=gi-vi;vsd=-vds
        path.append(vds*d[f'i(@b.xq{j}.bswitch[i])']+(extd-vi)**2/rd+(vs-ss)**2/rs)
        additional+=(ge-gi)**2/.4+vgs*diode(vgs)+vgd*diode(vgd)+(vds**2+vgs**2+vgd**2)/(1e11/1545)
        gate-=(ge-vs)*d[f'i(vg{j})'];vg.append(ge-vs);vd.append(vds)
        qgs=1.023e-9*si*vgs+.5*5.465e-10*si*.1861*soft((vgs-1.604)/.1861)+1.732e-10*si*10.55*soft((vsd-74.8)/10.55)
        qgd=1.942e-15*sr*vgd+.5*5.465e-10*si*.1861*soft((vgd-1.604)/.1861)+1.178e-13*sr*4.314*soft((vgd+5)/4.314)+7.786e-15*sr*15.29*soft((vgd+17.26)/15.29)+1.742e-15*sr*.89*soft((vgd+33.26)/.89)
        qsd=8.330e-11*so*vsd+4.297e-11*so*1.287*soft((vsd+14.35)/1.287)+1.155e-10*so*9.467*soft((vsd+20.14)/9.467)+4.647e-12*so*5.665*soft((vsd+81.25)/5.665)
        charge_energy+=sum(float(np.sum(.5*(v[1:]+v[:-1])*np.diff(q))) for v,q in [(vgs,qgs),(vgd,qgd),(vsd,qsd)])
    path=np.array(path).T;total=avg(path.sum(axis=1)+additional);splits=[]
    for width in [25e-9,50e-9,100e-9]:
        sums={'on_W':0.,'reverse_W':0.,'switching_W':0.,'off_W':0.}
        for j in range(6):
            mate=(j+3)%6;events=np.unique(meta['events'][str(j+1)]+meta['events'][str(mate+1)])
            tt=np.unique(np.r_[t,events[(events>=start)&(events<=end)],(events+width)[(events+width>=start)&(events+width<=end)]])
            mid=(tt[:-1]+tt[1:])/2;en=.5*(np.interp(tt[:-1],t,path[:,j])+np.interp(tt[1:],t,path[:,j]))*np.diff(tt)
            ix=np.searchsorted(events,mid,side='right')-1;sw=(ix>=0)&(mid-events[np.maximum(ix,0)]<width)
            on=(np.interp(mid,t,vg[j])>2.5)&~sw;rev=(np.interp(mid,t,vd[j])<0)&~sw&~on
            for key,mask in [('on_W',on),('reverse_W',rev),('switching_W',sw),('off_W',~(on|rev|sw))]:sums[key]+=float(en[mask].sum()/.02)
        splits.append({'window_ns':width*1e9,**sums})
    cur=np.loadtxt(G/(tag+'_current.csv'),delimiter=',');transfer=sum(d[f'v({p})']*np.interp(t,cur[:,0],cur[:,j+1]) for j,p in enumerate('abc'))
    residual=avg(-60*d['i(vdc)']+gate-transfer)-total-charge_energy/.02
    overlap_s=[float(np.trapezoid(((vg[j]>2.5)&(vg[j+3]>2.5)).astype(float),t)) for j in range(3)]
    assert max(overlap_s)<1e-10,(tag,overlap_s)
    return {'complete':True,'duration_s':.02,'deadtime_us':meta['deadtime']*1e6,'current_spacing_us':meta['current_spacing']*1e6,'device_W':total,'gate_path_leakage_W':avg(additional),'gate_source_W':avg(gate),'dc_source_W':avg(-60*d['i(vdc)']),'current_source_W':avg(transfer),'overlap_s':overlap_s,'charge_energy_J':charge_energy,'balance_residual_W':residual,'balance_residual_pct_loss':abs(residual)/total*100,'splits':splits}

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description='Integrate EPC2218 device losses over the complete 20 ms record.')
    parser.add_argument('cases', nargs='+', help='Case names generated by run_losses.py')
    args = parser.parse_args()
    results = {tag: analyze(tag) for tag in args.cases}
    (G/'losses.json').write_text(json.dumps(results, indent=2), encoding='utf8')
    print(json.dumps(results, indent=2))
